export function PaintingDetail({ lang, painting: p }) {
  const t = T[lang];
  const en = lang === 'en';
  const path = `${t.base}/${p.slug}`;
  const otherPath = `${t.otherBase}/${p.slug}`;
  const title = en ? p.titleEn : `《${p.titleZh}》`;
  const altTitle = en ? p.titleZh : p.titleEn;
  const artist = en ? p.artistEn : p.artistZh;
  const museum = en ? p.museumEn : p.museumZh;
  const intro = en ? p.introEn : p.introZh;
  const n = p.figures.length;

  const pageTitle = en
    ? `${p.titleEn} (${p.titleZh}) – ${p.dynastyEn} painting | RuHua`
    : `${p.titleZh}：画中人物与介绍 | 入画 RuHua`;
  const description = en
    ? `${p.titleEn} (${p.titleZh}), ${artist}. What the painting shows, who the ${n === 1 ? 'figure is' : `${n} figures are`}, and how to put yourself in it with the RuHua app.`
    : `${title}（${artist}）：画的是什么，画中${n === 1 ? '人物' : `${n}位人物`}是谁，以及如何用入画应用把自己放进画里。`;

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'VisualArtwork',
    name: en ? p.titleEn : p.titleZh,
    alternateName: en ? p.titleZh : p.titleEn,
    artform: 'Painting',
    image: SITE_URL + p.image,
    description: intro[0],
    url: SITE_URL + path,
    inLanguage: en ? 'en' : 'zh-Hans',
  };

  return (
    <div className={s.page} lang={en ? 'en' : 'zh-Hans'}>
      <Head>
        <title>{pageTitle}</title>
        <meta name="description" content={description} />
        <link rel="canonical" href={SITE_URL + path} />
        {alternates(`/paintings/${p.slug}`, `/zh/paintings/${p.slug}`)}
        <meta property="og:title" content={pageTitle} />
        <meta property="og:description" content={description} />
        <meta property="og:image" content={SITE_URL + p.image} />
        <meta property="og:url" content={SITE_URL + path} />
        <meta property="og:type" content="article" />
        <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }} />
      </Head>
      <div className={s.inner}>
        <Nav lang={lang} otherPath={otherPath} showAll />
        <header className={s.header}>
          <h1>{title}</h1>
          <p className={s.alt}>{altTitle}</p>
          <dl className={s.facts}>
            <dt>{t.period}</dt><dd>{en ? p.dateEn : p.dateZh}</dd>
            <dt>{t.artist}</dt><dd>{artist}</dd>
            {museum && <><dt>{t.heldAt}</dt><dd>{museum}</dd></>}
          </dl>
        </header>

        <figure className={s.figure}>
          <Image
            src={p.image}
            alt={en ? `${p.titleEn} (${p.titleZh})` : `${p.titleZh}`}
            width={p.width}
            height={p.height}
            sizes="(max-width: 760px) 100vw, 720px"
            priority
          />
        </figure>

        <div className={s.content}>
          <h2>{t.about}</h2>
          {intro.map((para, i) => <p key={i}>{para}</p>)}

          <h2>{t.people}</h2>
          <ul className={s.people}>
            {p.figures.map(f => (
              <li key={f.id}>
                <strong>{en ? `${f.nameEn} (${f.nameZh})` : f.nameZh}</strong>
                {en ? f.descEn : f.descZh}
              </li>
            ))}
          </ul>

          <section className={s.cta}>
            <h2>{t.ctaTitle}</h2>
            <p>{t.cta(n)}</p>
            <a className={s.button} href={APP_STORE_URL}>{t.button}</a>
            <p className={s.small}>
              {t.privacy[0]}<Link href="/privacy">{t.privacy[1]}</Link>{t.privacy[2]}
            </p>
          </section>
        </div>
        <Footer />
      </div>
      <SiteAnalytics />
    </div>
  );
}

